  const post = preflightRecord(a, 'post-push', { ok: true, providerCalls: 0, benchmarkHead: head });
  assert.equal(pre.sessionId, a);
  fs.writeFileSync(path.join(dir, 'preflight.json'), JSON.stringify(pre));
  fs.writeFileSync(path.join(dir, 'post-push-preflight.json'), JSON.stringify(post));
