'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const cp = require('node:child_process');
const crypto = require('node:crypto');
const { parseSessionId, sessionPath, assertUnusedSession, observationSlots, assertPreflightBinding, preflightRecord, assertObservationAvailable } = require('./session-identity.cjs');
const root = __dirname;
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'benchmark-manifest.json')));
const frozen = JSON.parse(cp.execFileSync('git', ['show', 'eb0b501ba6d106730ba15c0e7f3dc3a5e4f5b496:research/bounded-vs-codex-robustness-v1/benchmark-manifest.json'], { encoding: 'utf8' }));
const { sessionId: oldSession, ...definition } = frozen;
