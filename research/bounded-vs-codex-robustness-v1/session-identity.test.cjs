  assert.deepEqual(historical.map(id => fs.readdirSync(path.join(tmp, id))), oldBefore);
  const dir = sessionPath(tmp, a); fs.mkdirSync(dir);
  const firstObsDir = path.join(dir, 'observations', 'R1-normal');
  assert.doesNotThrow(() => assertObservationAvailable([], slotsA, 'R1-normal', firstObsDir));
  assert.throws(() => assertObservationAvailable([], slotsA, 'R1-bounded', firstObsDir), /order/);
  const completed = [{ sessionId: a, observationId: slotsA[0].observationId, obsId: 'R1-normal', state: 'completed' }];
  assert.doesNotThrow(() => assertObservationAvailable(completed, slotsA, 'R1-bounded', path.join(dir, 'observations', 'R1-bounded')));
  assert.throws(() => assertObservationAvailable(completed, slotsA, 'R1-normal', firstObsDir), /consumed/);
  assert.throws(() => assertObservationAvailable([{ ...completed[0], state: 'reserved' }], slotsA, 'R1-bounded', firstObsDir), /consumed/);
  fs.mkdirSync(path.dirname(firstObsDir)); fs.mkdirSync(firstObsDir);
  assert.throws(() => assertObservationAvailable([], slotsA, 'R1-normal', firstObsDir), /consumed/);
  fs.rmSync(firstObsDir, { recursive: true }); fs.rmdirSync(path.dirname(firstObsDir));
  const head = 'f'.repeat(40);
