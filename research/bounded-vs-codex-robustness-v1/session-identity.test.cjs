  for (const id of historical) fs.mkdirSync(path.join(tmp, id));
  const oldBefore = historical.map(id => fs.readdirSync(path.join(tmp, id)));
  for (const id of historical.slice(1)) assert.throws(() => assertUnusedSession(tmp, id), /already exists/);
