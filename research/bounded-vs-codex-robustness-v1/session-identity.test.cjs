for (const task of manifest.tasks) {
  const { taskHash, ...content } = task;
  assert.equal(taskHash, `sha256:${crypto.createHash('sha256').update(canonical(content)).digest('hex')}`);
  assert.equal(taskHash, frozen.tasks.find(t => t.taskId === task.taskId).taskHash);
  assert.equal(task.model, manifest.model); assert.equal(task.reasoning, manifest.reasoning);
  assert.equal(task.sourceHead, manifest.sourceHead);
  assert.equal(task.policy.retry + task.policy.repair + task.policy.apply, 0);
}
assert.deepEqual(manifest.tasks.map(t => t.difficulty), ['easy','medium_a','medium_b','medium_c','hard']);
assert.deepEqual(manifest.tasks.map(t => t.order), [['normal','bounded'],['bounded','normal'],['normal','bounded'],['bounded','normal'],['normal','bounded']]);
const a = 'robustness-v1-2026-09-29-r5', b = 'robustness-v1-2026-09-29-r6';
assert.equal(parseSessionId(['--session-id', a]), a);
assert.equal(parseSessionId([`--session-id=${a}`]), a);
